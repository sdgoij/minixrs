//! Post-link image steps: the x86 trampoline, and the raw disk image.
//!
//! `crates/kernel/build.rs` assembles the initramfs and the MinixFS images, but a
//! build script cannot do post-link work: the trampoline needs the linked kernel's
//! `kmain` address, and it embeds the kernel as a loadable section. That is
//! [`mkboot`]. [`mkfs`] copies the kernel's MinixFS blob to the per-arch disk
//! image QEMU attaches, so one arch's build never clobbers another's.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::arch::{self, Arch};
use crate::cc;
use crate::toolchain;

// The tool lookups the fork's build tree answers: `rust-lld`, `rust-objcopy` and
// `llvm-nm` live there, and a CI image has none of them on PATH.
#[path = "../../kernel-boot/toolchain_tools.rs"]
mod toolchain_tools;

pub fn mkboot(root: &Path, features: Option<&str>, stem: Option<&str>) -> io::Result<()> {
    let stem = stem.unwrap_or("kernel");
    let features = features_of(features);
    println!("Features: {features}");

    let host = toolchain_tools::host_triple();
    let dirs = toolchain_tools::tool_dirs(root, &host);
    let stage1 = toolchain::find_stage1_rustc(root).ok_or_else(toolchain::missing_stage1)?;
    let nm = tool(&dirs, &["rust-nm", "llvm-nm"], "nm")?;
    let objcopy = tool(&dirs, &["rust-objcopy", "llvm-objcopy"], "objcopy")?;
    let lld = tool(&dirs, &["rust-lld", "lld"], "lld")?;
    let clang = tool(&dirs, &["clang"], "clang")?;

    // 1. Build the kernel with the rust fork's stage1 compiler; the in-tree target
    //    provides core/alloc/std from its sysroot, and the linker script comes from
    //    `.cargo/config.toml`.
    let mut build = Command::new(toolchain::cargo());
    build
        .current_dir(root)
        .env("RUSTC", &stage1)
        .args([
            "build",
            "-p",
            "kernel-boot",
            "--target",
            "x86_64-pc-minix",
            "--features",
            &features,
            "--release",
        ]);
    run(&mut build, "building kernel-boot")?;

    // 2. Extract the kmain address from the linked ELF.
    let kernel_elf = root
        .join("target")
        .join("x86_64-pc-minix")
        .join("release")
        .join("kernel-boot");
    let output = Command::new(&nm)
        .args(["-n", &kernel_elf.to_string_lossy()])
        .output()
        .map_err(|error| {
            io::Error::new(error.kind(), format!("running {}: {error}", nm.display()))
        })?;
    let kmain = parse_kmain(&String::from_utf8_lossy(&output.stdout)).ok_or_else(|| {
        io::Error::other(format!(
            "kmain symbol not found in {}; did the kernel build fail?",
            kernel_elf.display()
        ))
    })?;
    println!("kmain @ 0x{kmain}");

    // 3. objcopy the kernel to a raw binary. This happens before the trampoline
    //    link because that binary is linked into the trampoline ELF as its own
    //    loadable segment, which is what makes the ELF a single boot artifact.
    let kernel_bin = root.join("target").join(format!("{stem}.bin"));
    let mut objcopy_command = Command::new(&objcopy);
    objcopy_command.args([
        "-O",
        "binary",
        &kernel_elf.to_string_lossy(),
        &kernel_bin.to_string_lossy(),
    ]);
    run(&mut objcopy_command, "objcopy")?;
    println!("{} written", kernel_bin.display());

    // 4. Build the trampoline with the correct address.
    let kernel_boot = root.join("crates").join("kernel-boot");
    let trampoline_obj = root.join("target").join("trampoline_.o");
    let trampoline_name = if stem == "kernel" {
        "trampoline.elf".to_string()
    } else {
        format!("{stem}-trampoline.elf")
    };
    let trampoline_elf = root.join("target").join(trampoline_name);

    let mut trampoline = Command::new(&clang);
    trampoline.args([
        "-c",
        "-target",
        "i386-pc-none-elf",
        "-m32",
        &format!("-DKMAIN=0x{kmain}"),
        "-o",
        &trampoline_obj.to_string_lossy(),
        &kernel_boot
            .join("src")
            .join("trampoline.S")
            .to_string_lossy(),
    ]);
    run(&mut trampoline, "compiling the trampoline")?;

    // The kernel image rides along as a second object: a stub that `.incbin`s the
    // raw binary into the `.kernel` output section, which `trampoline.ld` places at
    // 0x200000.
    let blob_s = root.join("target").join(format!("{stem}-kernel.S"));
    let blob_o = root.join("target").join(format!("{stem}-kernel.o"));
    fs::write(
        &blob_s,
        format!(
            "/* Generated by `cargo xtask image mkboot`: the kernel image as a loadable section. */\n\
             .section .kernel, \"a\"\n\
             .incbin \"{}\"\n",
            kernel_bin.to_string_lossy().replace('\\', "/")
        ),
    )?;

    let mut blob = Command::new(&clang);
    blob.args([
        "-c",
        "-target",
        "i386-pc-none-elf",
        "-m32",
        "-o",
        &blob_o.to_string_lossy(),
        &blob_s.to_string_lossy(),
    ]);
    run(&mut blob, "assembling the kernel blob")?;

    let mut link = Command::new(&lld);
    link.args([
        "-flavor",
        "gnu",
        "-m",
        "elf_i386",
        "-T",
        &kernel_boot.join("trampoline.ld").to_string_lossy(),
        "-o",
        &trampoline_elf.to_string_lossy(),
        &trampoline_obj.to_string_lossy(),
        &blob_o.to_string_lossy(),
    ]);
    run(&mut link, "linking the trampoline")?;

    for leftover in [&trampoline_obj, &blob_o, &blob_s] {
        let _ = fs::remove_file(leftover);
    }
    println!("Trampoline rebuilt with kmain @ 0x{kmain}");
    Ok(())
}

pub fn mkfs(root: &Path, target: Option<&str>) -> io::Result<()> {
    let arch = match target {
        Some(token) => arch::resolve(token)?,
        None => arch::DEFAULT,
    };
    copy_disk_image(root, arch)
}

fn copy_disk_image(root: &Path, arch: &Arch) -> io::Result<()> {
    let images = root.join("target").join("images").join(arch.triple);
    let source = images.join("minixfs.img");
    let bytes = fs::read(&source).map_err(|error| {
        io::Error::new(
            error.kind(),
            format!(
                "reading {}: {error} — build the kernel first (`just build {}`)",
                source.display(),
                arch.name
            ),
        )
    })?;
    let destination = images.join("disk.img");
    fs::write(&destination, &bytes)?;
    println!("mkfs: wrote {} ({} bytes)", destination.display(), bytes.len());
    Ok(())
}

/// The feature list for `kernel-boot`.
///
/// `embed_minixfs` is not forced: a boot image for a disk-root boot embeds only the
/// initramfs, and the root filesystem is a separate system image. `x86` gates the
/// `kernel-boot` bin, because a plain workspace build must skip the no_main kernel
/// image.
fn features_of(given: Option<&str>) -> String {
    let Some(given) = given else {
        return "embed_initramfs,x86".to_string();
    };
    let mut all = given.to_string();
    if !all.contains("embed_initramfs") {
        all = format!("embed_initramfs,{all}");
    }
    if !all.split(',').any(|feature| feature == "x86") {
        all = format!("{all},x86");
    }
    all
}

/// The `kmain` address in `nm -n` output: the third field of the line whose
/// symbol is `kmain`.
fn parse_kmain(output: &str) -> Option<String> {
    output.lines().find_map(|line| {
        let fields: Vec<&str> = line.split_whitespace().collect();
        (fields.len() >= 3 && fields[2] == "kmain").then(|| fields[0].to_string())
    })
}

fn tool(dirs: &[PathBuf], names: &[&str], what: &str) -> io::Result<PathBuf> {
    toolchain_tools::find_tool(dirs, names).ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::NotFound,
            format!(
                "no {what} found (tried {}, then PATH); run `just bootstrap` to build the fork's toolchain, or install LLVM",
                names.join(", ")
            ),
        )
    })
}

fn run(command: &mut Command, what: &str) -> io::Result<()> {
    if cc::run(command)? {
        Ok(())
    } else {
        Err(io::Error::other(format!("{what} failed")))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_default_features_are_the_initramfs_on_x86() {
        assert_eq!(features_of(None), "embed_initramfs,x86");
    }

    #[test]
    fn the_initramfs_and_the_x86_gate_are_added_when_missing() {
        assert_eq!(
            features_of(Some("embed_minixfs")),
            "embed_initramfs,embed_minixfs,x86"
        );
        assert_eq!(
            features_of(Some("embed_initramfs,embed_minixfs,boot-test")),
            "embed_initramfs,embed_minixfs,boot-test,x86"
        );
        assert_eq!(
            features_of(Some("boot-test,x86")),
            "embed_initramfs,boot-test,x86"
        );
    }

    #[test]
    fn kmain_is_the_address_on_its_own_line() {
        let output = "\
0000000000200000 T _start
0000000000201000 T kmain
0000000000202000 T other
";
        assert_eq!(parse_kmain(output).as_deref(), Some("0000000000201000"));
    }

    #[test]
    fn a_missing_kmain_is_none() {
        assert_eq!(parse_kmain("0000000000200000 T _start\n"), None);
    }
}
