//! Cross-build clang and LLD for a minix target, and stage the toolchain root.
//!
//! This is Phase 2 and Phase 3 of `.notes/toolchain_in_os.md`: one CMake build
//! per arch against `rust/src/llvm-project/llvm`, with the build host's tablegen
//! (`crate::build::llvm_host`), a generated toolchain file, and `crate::minix_ld`
//! as the link rule. The products are a bare-metal `clang` and `lld` that run
//! *inside* the guest, plus the root the guest needs to use them: headers,
//! `libc.a`, the C++ runtime, `crt0.o` and the linker script.
//!
//! `/usr/bin/clang` is not the driver renamed. The driver is at
//! `/usr/libexec/clang-driver`, and `/usr/bin/clang` is `tools/clang-wrapper.c`:
//! a link line needs `crt0.o`, the archives, the script and the image bases, and a
//! `-c` line must not be handed them. That cannot be expressed in a config file.
//!
//! Output: `target/llvm-<arch>/{build,toolchain.cmake}`, and the staged root at
//! `target/toolchain/<arch>/root` (shipped on the disk path only: the embedded
//! ramdisk window is 16 MiB).
//!
//! What has to already exist, and is reported by name when it does not: the host
//! tablegen (`just llvm-host-tools`), the C++ runtime
//! (`cargo xtask build libcxx-toolchain` + the libcxx build, see
//! `crate::build::libcxx`), and a host `ld.lld` for the driver's own link.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::arch::{self, Arch};
use crate::build::{libc_static, llvm_host};
use crate::cc;
use crate::toolchain;

/// The archs this builds for. Clang for `aarch64-unknown-none` needs the AArch64
/// backend; only x86_64 has been carried through the whole toolchain so far, and
/// claiming the others before a gate runs them is worse than saying so.
const ARCHES: [&str; 1] = ["x86"];

/// The LLVM backend a cross build needs: the guest's own target.
fn llvm_targets(arch: &Arch) -> &'static str {
    match arch.name {
        "x86" => "X86",
        "riscv64" => "RISCV",
        "aarch64" => "AArch64",
        other => unreachable!("no LLVM target named for {other}"),
    }
}

/// Where the cross build and its toolchain file live.
pub fn out_dir(root: &Path, arch: &Arch) -> PathBuf {
    root.join("target").join(format!("llvm-{}", arch.name))
}

pub fn build_dir(root: &Path, arch: &Arch) -> PathBuf {
    out_dir(root, arch).join("build")
}

pub fn toolchain_file(root: &Path, arch: &Arch) -> PathBuf {
    out_dir(root, arch).join("toolchain.cmake")
}

/// Where the guest's tree is staged.
pub fn stage_root(root: &Path, arch: &Arch) -> PathBuf {
    root.join("target")
        .join("toolchain")
        .join(arch.name)
        .join("root")
}

/// The major version of the LLVM sources, which is the directory name clang
/// looks for under `lib/clang`.
pub fn resource_major(version: &str) -> String {
    version.split('.').next().unwrap_or(version).to_string()
}

/// The CMake toolchain file for one arch.
///
/// `CMAKE_SYSTEM_NAME Linux` and not `Generic`, and on purpose: with `Generic`,
/// `LLVM_ON_UNIX` stays off and LLVM's `file_status` compiles against Windows
/// code paths inside a guest that has no Windows. The platform is Unix-shaped;
/// only the C library is not a host one, and the flags below are what keep it out.
pub fn toolchain_text(root: &Path, arch: &Arch, xtask: &Path, lld: &Path) -> String {
    let root = root.to_string_lossy().replace('\\', "/");
    let xtask = xtask.to_string_lossy().replace('\\', "/");
    let lld = lld.to_string_lossy().replace('\\', "/");
    let machine = arch.machine;
    let name = arch.name;
    let triple = arch.clang_target();
    let minix_triple = arch.triple;
    let libcxx_include = format!(
        "${{MINIX_ROOT}}/target/cxx/{name}-toolchain/libcxx-build/include/c++/v1"
    );
    let link = format!(
        "{xtask} minix-ld --arch {name} --out <TARGET> \
         --crt0 \\\"${{MINIX_CRT0}}\\\" --libc \\\"${{MINIX_LIBC}}\\\" \
         --libstdcxx \\\"${{MINIX_LIBCXX}}\\\" --script \\\"${{MINIX_SCRIPT}}\\\" \
         --lld \\\"{lld}\\\"",
        name = arch.name,
    );
    format!(
        "\
# Generated by `cargo xtask build llvm-minix`. Do not edit.
set(CMAKE_SYSTEM_NAME Linux)
set(CMAKE_SYSTEM_PROCESSOR {machine})
set(CMAKE_TRY_COMPILE_TARGET_TYPE STATIC_LIBRARY)

# The platform is Unix, but nothing host-shaped may leak into a link.
set(CMAKE_DL_LIBS \"\")
set(CMAKE_THREAD_LIBS_INIT \"\")

set(MINIX_ROOT \"{root}\")
set(MINIX_LLVM \"${{MINIX_ROOT}}/rust/src/llvm-project\")
set(MINIX_CRT0 \"${{MINIX_ROOT}}/target/c-direct/{name}/crt0.o\")
set(MINIX_LIBC \"${{MINIX_ROOT}}/target/{minix_triple}/release/libc.a\")
set(MINIX_LIBCXX \"${{MINIX_ROOT}}/target/cxx/{name}-toolchain/minix-runtime/libstdc++.a\")
set(MINIX_SCRIPT \"${{MINIX_ROOT}}/tools/minix-user.ld\")

find_program(MINIX_CLANG clang REQUIRED)
find_program(MINIX_CLANGXX clang++ REQUIRED)
find_program(MINIX_AR llvm-ar REQUIRED)
find_program(MINIX_RANLIB llvm-ranlib REQUIRED)
execute_process(COMMAND \"${{MINIX_CLANG}}\" -print-resource-dir
                OUTPUT_VARIABLE MINIX_RESOURCE
                OUTPUT_STRIP_TRAILING_WHITESPACE)

set(MINIX_C_FLAGS \"-ffreestanding -mno-red-zone -fno-stack-protector -fno-pic -O2 -nostdinc -isystem \\\"${{MINIX_RESOURCE}}/include\\\" -I\\\"${{MINIX_ROOT}}/tools/c-include\\\"\")
# libc++ before the C headers: its wrappers (`errno.h`, `math.h`, `stdio.h`)
# `include_next` the C header, so the C tree has to come after them.
set(MINIX_CXX_FLAGS \"-D_LIBCPP_PROVIDES_DEFAULT_RUNE_TABLE -D_LIBCPP_NO_ABI_TAG -ffreestanding -mno-red-zone -fno-stack-protector -fno-pic -O2 -nostdinc -nostdinc++ -isystem \\\"${{MINIX_LLVM}}/libcxx/include\\\" -isystem \\\"${{MINIX_LLVM}}/libcxxabi/include\\\" -I\\\"{libcxx_include}\\\" -isystem \\\"${{MINIX_RESOURCE}}/include\\\" -I\\\"${{MINIX_ROOT}}/tools/c-include\\\"\")

set(CMAKE_C_COMPILER \"${{MINIX_CLANG}}\")
set(CMAKE_CXX_COMPILER \"${{MINIX_CLANGXX}}\")
set(CMAKE_AR \"${{MINIX_AR}}\")
set(CMAKE_RANLIB \"${{MINIX_RANLIB}}\")
set(CMAKE_C_COMPILER_TARGET \"{triple}\")
set(CMAKE_CXX_COMPILER_TARGET \"{triple}\")
set(CMAKE_C_FLAGS_INIT \"${{MINIX_C_FLAGS}}\")
set(CMAKE_CXX_FLAGS_INIT \"${{MINIX_CXX_FLAGS}}\")

set(CMAKE_ASM_COMPILER \"${{MINIX_CLANG}}\")
set(CMAKE_ASM_COMPILER_TARGET \"{triple}\")
set(CMAKE_ASM_FLAGS_INIT \"-ffreestanding -mno-red-zone -fno-stack-protector -fno-pic\")

set(CMAKE_C_COMPILER_WORKS 1)
set(CMAKE_CXX_COMPILER_WORKS 1)

set(CMAKE_FIND_ROOT_PATH \"${{MINIX_ROOT}}\")
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)

# CMake's own link rule would hand the line to the host's clang, which falls
# back to the host's linker and libc for this triple. `xtask minix-ld` is the
# Phase 0 link line: the script, `crt0.o`, `libc.a`, `libstdc++.a` and the bases.
set(MINIX_LINK_CMD \"{link}\")
set(CMAKE_C_LINK_EXECUTABLE \"${{MINIX_LINK_CMD}} <LINK_FLAGS> <OBJECTS> <LINK_LIBRARIES>\")
set(CMAKE_CXX_LINK_EXECUTABLE \"${{MINIX_LINK_CMD}} <LINK_FLAGS> <OBJECTS> <LINK_LIBRARIES>\")
",
    )
}

/// A path as CMake spells it. Windows separators in a `-D` value survive, but
/// they make the generated cache disagree with every other path in the tree.
fn slash(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}

/// The configure arguments. Every one of these is a cached answer the build
/// cannot discover on its own: it probes by *running* programs, and these are
/// minix programs.
pub fn cmake_args(root: &Path, arch: &Arch, host_tools: &Path) -> Vec<String> {
    let build = build_dir(root, arch);
    let file = toolchain_file(root, arch);
    let mut args = vec![
        "-G".to_string(),
        "Ninja".to_string(),
        "-S".to_string(),
        slash(&root.join("rust/src/llvm-project/llvm")),
        "-B".to_string(),
        slash(&build),
    ];
    for option in [
        format!("-DCMAKE_TOOLCHAIN_FILE={}", slash(&file)),
        "-DCMAKE_BUILD_TYPE=Release".to_string(),
        "-DCMAKE_CROSSCOMPILING=ON".to_string(),
        "-DLLVM_ENABLE_PROJECTS=clang;lld".to_string(),
        format!("-DLLVM_TARGETS_TO_BUILD={}", llvm_targets(arch)),
        format!("-DLLVM_DEFAULT_TARGET_TRIPLE={}", arch.clang_target()),
        format!("-DLLVM_NATIVE_TOOL_DIR={}", slash(host_tools)),
        format!(
            "-DLLVM_HOST_TRIPLE={}",
            toolchain::host_triple().unwrap_or_else(|| "x86_64-pc-windows-msvc".to_string())
        ),
        // The port has one C library and no separate `libatomic`: the answers
        // are known, and a configure test that runs a program cannot find them.
        "-DHAVE_CXX_ATOMICS_WITHOUT_LIB=1".to_string(),
        "-DHAVE_CXX_ATOMICS64_WITHOUT_LIB=1".to_string(),
        "-DLLVM_HAS_ATOMICS=1".to_string(),
        "-DLLVM_ENABLE_LIBCXX=ON".to_string(),
        "-DLLVM_ENABLE_THREADS=OFF".to_string(),
        "-DLLVM_ENABLE_EH=OFF".to_string(),
        "-DLLVM_ENABLE_RTTI=OFF".to_string(),
        "-DLLVM_ENABLE_PIC=OFF".to_string(),
        "-DLLVM_ENABLE_PLUGINS=OFF".to_string(),
        "-DCLANG_PLUGIN_SUPPORT=OFF".to_string(),
        "-DLLVM_ENABLE_ZLIB=OFF".to_string(),
        "-DLLVM_ENABLE_ZSTD=OFF".to_string(),
        "-DLLVM_ENABLE_TERMINFO=OFF".to_string(),
        "-DLLVM_ENABLE_LIBXML2=OFF".to_string(),
        "-DLLVM_ENABLE_LIBEDIT=OFF".to_string(),
        "-DBUILD_SHARED_LIBS=OFF".to_string(),
        "-DLLVM_BUILD_LLVM_DYLIB=OFF".to_string(),
        "-DLLVM_BUILD_TOOLS=OFF".to_string(),
        "-DLLVM_INCLUDE_TESTS=OFF".to_string(),
        "-DLLVM_INCLUDE_BENCHMARKS=OFF".to_string(),
        "-DLLVM_INCLUDE_EXAMPLES=OFF".to_string(),
        "-DLLVM_INCLUDE_DOCS=OFF".to_string(),
        "-DCLANG_ENABLE_ARCMT=OFF".to_string(),
        "-DCLANG_ENABLE_STATIC_ANALYZER=OFF".to_string(),
    ] {
        args.push(option);
    }
    args
}

/// The `libstdc++.a` the link rule names.
fn runtime_archive(root: &Path, arch: &Arch) -> PathBuf {
    root.join("target")
        .join("cxx")
        .join(format!("{}-toolchain", arch.name))
        .join("minix-runtime")
        .join("libstdc++.a")
}

/// `crt0.o` for the link rule, in the directory `cargo xtask build c-direct`
/// uses, so the two commands share one artifact (same flags, same file).
fn crt0(root: &Path, arch: &Arch) -> PathBuf {
    root.join("target")
        .join("c-direct")
        .join(arch.name)
        .join("crt0.o")
}

pub fn run(root: &Path, target: Option<&str>) -> io::Result<()> {
    let arch = arch::resolve(target.unwrap_or(ARCHES[0]))?;
    if !ARCHES.contains(&arch.name) {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            format!(
                "llvm-minix: no toolchain build for {} yet (carried through: {})",
                arch.name,
                ARCHES.join(", ")
            ),
        ));
    }
    let lld = toolchain::find_lld(root).ok_or_else(toolchain::missing_lld)?;
    let cmake = need("cmake")?;
    need("ninja")?;

    let host_tools = llvm_host::bin_dir(root);
    let tablegen = host_tools.join(toolchain::exe("clang-tblgen"));
    if !tablegen.is_file() {
        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            format!(
                "{} is missing: run `just llvm-host-tools` first (a cross build of clang runs the build host's tablegen, and it must be the same LLVM)",
                tablegen.display()
            ),
        ));
    }
    let libstdcxx = runtime_archive(root, arch);
    if !libstdcxx.is_file() {
        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            format!(
                "{} is missing: build the C++ runtime for the toolchain first (`just cxx-toolchain {name}`, see .notes/toolchain_in_os.md)",
                libstdcxx.display(),
                name = arch.name
            ),
        ));
    }

    // The archives and `crt0.o` are named by the CMake link rule, so they have
    // to exist before the first link, not after the build.
    let libc = libc_static::archive(root, arch)?;
    let crt0 = crt0(root, arch);
    compile_crt0(root, arch, &crt0)?;

    let version = llvm_host::source_version(root)?;
    let file = toolchain_file(root, arch);
    if let Some(parent) = file.parent() {
        fs::create_dir_all(parent)?;
    }
    let xtask = std::env::current_exe()?;
    fs::write(&file, toolchain_text(root, arch, &xtask, &lld))?;
    println!("wrote {}", file.display());

    let mut configure = Command::new(&cmake);
    configure.args(cmake_args(root, arch, &host_tools));
    step(&mut configure, "configuring the cross build")?;

    let build = build_dir(root, arch);
    let mut build_command = Command::new(&cmake);
    build_command.arg("--build").arg(&build);
    for target in ["clang", "lld"] {
        build_command.arg("--target").arg(target);
    }
    build_command.args(["--parallel", "16"]);
    step(&mut build_command, "building clang and lld")?;

    let driver = build.join("bin").join("clang");
    let guest_lld = build.join("bin").join("ld.lld");
    let guest_lld = if guest_lld.is_file() {
        guest_lld
    } else {
        // LLVM 23 links one `lld` and copies it to the flavour names; a host
        // whose CMake skipped the copies still has the driver.
        build.join("bin").join("lld")
    };
    for path in [&driver, &guest_lld] {
        if !path.is_file() {
            return Err(io::Error::new(
                io::ErrorKind::NotFound,
                format!("{} was not produced", path.display()),
            ));
        }
    }

    let wrapper = build_wrapper(root, arch, &lld, &libc, &crt0)?;
    stage(root, arch, &driver, &guest_lld, &wrapper, &libc, &libstdcxx, &crt0, &version)?;
    println!(
        "toolchain: {} staged at {}",
        arch.name,
        stage_root(root, arch).display()
    );
    Ok(())
}

/// `crt0.o` for the target, compiled the way `cargo xtask build c-direct` does.
fn compile_crt0(root: &Path, arch: &Arch, out: &Path) -> io::Result<()> {
    if let Some(parent) = out.parent() {
        fs::create_dir_all(parent)?;
    }
    let mut flags = arch.base_cflags();
    flags.extend(["-fno-builtin", "-O2", "-c"].map(String::from));
    flags.extend(cc::compile_flags(root)?);
    let mut command = Command::new("clang");
    command
        .args(&flags)
        .arg("-o")
        .arg(out)
        .arg(arch.crt0(root));
    step(&mut command, "compiling crt0")?;
    Ok(())
}

/// Compile and link `tools/clang-wrapper.c` for the guest.
fn build_wrapper(
    root: &Path,
    arch: &Arch,
    lld: &Path,
    libc: &Path,
    crt0: &Path,
) -> io::Result<PathBuf> {
    let work = build_dir(root, arch);
    let object = work.join("clang-wrapper.o");
    let out = work.join("clang-wrapper");

    let mut flags = arch.base_cflags();
    flags.extend(["-fno-builtin", "-O2", "-c"].map(String::from));
    flags.extend(cc::compile_flags(root)?);
    let target = format!("{}-elf", arch.clang_target());
    for (name, value) in [
        ("MINIX_DRIVER", "/usr/libexec/clang".to_string()),
        ("MINIX_INSTALL_DIR", "/usr/libexec".to_string()),
        ("MINIX_TARGET", target),
        ("MINIX_CRT0", "/usr/lib/crt0.o".to_string()),
        ("MINIX_SCRIPT", "/usr/lib/minix-user.ld".to_string()),
        ("MINIX_LIBC", "/usr/lib/libc.a".to_string()),
        ("MINIX_LIBCXX", "/usr/lib/libstdc++.a".to_string()),
        ("MINIX_LD", "/usr/bin/ld.lld".to_string()),
        ("MINIX_IMAGE_BASE", arch.image_base.to_string()),
        ("MINIX_LOADER_BASE", arch.loader_base.to_string()),
    ] {
        flags.push(format!("-D{name}=\"{value}\""));
    }
    let mut command = Command::new("clang");
    command
        .args(&flags)
        .arg("-o")
        .arg(&object)
        .arg(root.join("tools").join("clang-wrapper.c"));
    step(&mut command, "compiling the clang wrapper")?;

    let mut link = Command::new(lld);
    link.args([
        "-flavor",
        "gnu",
        "-o",
        &out.to_string_lossy(),
        &format!("--image-base={}", arch.image_base),
        &format!("--defsym=BASE_ADDRESS={}", arch.image_base),
        &format!("--defsym=LOADER_BASE={}", arch.loader_base),
        "-T",
        &root.join("tools").join("minix-user.ld").to_string_lossy(),
        "-z",
        "norelro",
        "--no-eh-frame-hdr",
        &crt0.to_string_lossy(),
        &object.to_string_lossy(),
        &libc.to_string_lossy(),
    ]);
    step(&mut link, "linking the clang wrapper")?;
    Ok(out)
}

/// Copy the toolchain into `target/toolchain/<arch>/root`.
#[allow(clippy::too_many_arguments)]
fn stage(
    root: &Path,
    arch: &Arch,
    driver: &Path,
    guest_lld: &Path,
    wrapper: &Path,
    libc: &Path,
    libstdcxx: &Path,
    crt0: &Path,
    version: &str,
) -> io::Result<()> {
    let stage = stage_root(root, arch);
    // Rebuilt, not merged: a header that is no longer part of the toolchain must
    // not survive in the image the gate boots.
    if stage.exists() {
        fs::remove_dir_all(&stage)?;
    }
    let usr_bin = stage.join("usr/bin");
    let usr_lib = stage.join("usr/lib");
    let usr_libexec = stage.join("usr/libexec");
    let usr_src = stage.join("usr/src");
    for dir in [&usr_bin, &usr_lib, &usr_libexec, &usr_src] {
        fs::create_dir_all(dir)?;
    }

    FS_EXE.copy(wrapper, &usr_bin.join("clang"))?;
    FS_EXE.copy(wrapper, &usr_bin.join("clang++"))?;
    FS_EXE.copy(guest_lld, &usr_bin.join("ld.lld"))?;
    FS_EXE.copy(driver, &usr_libexec.join("clang"))?;

    copy_tree(&root.join("tools/c-include"), &stage.join("usr/include"))?;
    let libcxx = root
        .join("target")
        .join("cxx")
        .join(format!("{}-toolchain", arch.name))
        .join("libcxx-build")
        .join("include")
        .join("c++")
        .join("v1");
    copy_tree(&libcxx, &stage.join("usr/include/c++/v1"))?;
    // The ABI headers are not installed by the libc++ build, and `__cxxabi_config.h`
    // comes from the libc++abi build.
    let abi = root.join("rust/src/llvm-project/libcxxabi/include");
    for entry in fs::read_dir(&abi)? {
        let path = entry?.path();
        if path.extension().and_then(|ext| ext.to_str()) == Some("h") {
            fs::copy(&path, stage.join("usr/include/c++/v1").join(path.file_name().unwrap()))?;
        }
    }
    let resource = root.join("rust/src/llvm-project/clang/lib/Headers");
    copy_tree(
        &resource,
        &stage.join("usr/lib/clang").join(resource_major(version)).join("include"),
    )?;

    fs::copy(libc, usr_lib.join("libc.a"))?;
    fs::copy(libstdcxx, usr_lib.join("libstdc++.a"))?;
    fs::copy(crt0, usr_lib.join("crt0.o"))?;
    fs::copy(
        root.join("tools/minix-user.ld"),
        usr_lib.join("minix-user.ld"),
    )?;
    fs::copy(root.join("tools/hello.c"), usr_src.join("hello.c"))?;
    fs::copy(root.join("tools/hello-cpp.cpp"), usr_src.join("hello.cpp"))?;

    // One translation unit per C++ header the toolchain has to get right; a
    // wrong search order shows up here before it reaches LLVM.
    let cxx_src = usr_src.join("cxx");
    fs::create_dir_all(&cxx_src)?;
    for name in ["cstddef.cpp", "algorithm.cpp", "vector.cpp"] {
        fs::copy(root.join("tools/cxx").join(name), cxx_src.join(name))?;
    }

    // Phase 4's first target: FileCheck, two real LLVM translation units the
    // guest compiles itself and links against the cross build's Support archive.
    // The include tree is the source headers with the build's generated files
    // overlaid, which is the include order the cross build used.
    let build = build_dir(root, arch);
    let llvm_include = stage.join("usr/lib/llvm/include");
    copy_tree(
        &root.join("rust/src/llvm-project/llvm/include"),
        &llvm_include,
    )?;
    copy_tree(&build.join("include"), &llvm_include)?;
    fs::copy(
        build.join("lib/libLLVMSupport.a"),
        stage.join("usr/lib/llvm/libLLVMSupport.a"),
    )?;

    let llvm = root.join("rust/src/llvm-project/llvm");
    let llvm_src = stage.join("usr/src/llvm");
    fs::create_dir_all(&llvm_src)?;
    fs::copy(
        llvm.join("lib/FileCheck/FileCheck.cpp"),
        llvm_src.join("filecheck-lib.cpp"),
    )?;
    fs::copy(
        llvm.join("lib/FileCheck/FileCheckImpl.h"),
        llvm_src.join("FileCheckImpl.h"),
    )?;
    fs::copy(
        llvm.join("utils/FileCheck/FileCheck.cpp"),
        llvm_src.join("filecheck-main.cpp"),
    )?;
    fs::copy(
        root.join("tools/filecheck-input.txt"),
        llvm_src.join("fc-input.txt"),
    )?;
    fs::copy(
        root.join("tools/filecheck-fail.check"),
        llvm_src.join("fc-fail.check"),
    )?;
    // Response files keep the guest's command lines short: the driver expands
    // them, and `-c` stays on the line so the wrapper knows this is a compile.
    for name in ["fc-lib.rsp", "fc-main.rsp", "fc-link.rsp"] {
        fs::copy(root.join("tools/cxx").join(name), llvm_src.join(name))?;
    }
    Ok(())
}

/// Permissions for an executable the guest is meant to run.
///
/// The image builder gives every file it packs `0755`, so this is not what makes
/// `/usr/bin/clang` runnable; it only keeps the *staged* tree usable on the host
/// (a wrapper you cannot run is a wrapper you cannot debug).
struct Executable;

const FS_EXE: Executable = Executable;

impl Executable {
    fn copy(&self, from: &Path, to: &Path) -> io::Result<()> {
        fs::copy(from, to)?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(to, fs::Permissions::from_mode(0o755))?;
        }
        Ok(())
    }
}

/// Copy a directory's contents, recursively. A missing source is an error: a
/// toolchain root without its headers would build nothing in the guest, and
/// silently shipping it is how that turns into a mysterious compile error.
fn copy_tree(from: &Path, to: &Path) -> io::Result<()> {
    fs::create_dir_all(to)?;
    for entry in fs::read_dir(from).map_err(|error| {
        io::Error::new(
            error.kind(),
            format!("reading {}: {error}", from.display()),
        )
    })? {
        let path = entry?.path();
        let name = path.file_name().unwrap().to_owned();
        let target = to.join(name);
        if path.is_dir() {
            copy_tree(&path, &target)?;
        } else {
            fs::copy(&path, &target)?;
        }
    }
    Ok(())
}

fn need(name: &str) -> io::Result<PathBuf> {
    toolchain::find_on_path(name).ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::NotFound,
            format!("`{name}` not found on PATH (needed by the cross build of LLVM)"),
        )
    })
}

fn step(command: &mut Command, what: &str) -> io::Result<()> {
    if cc::run(command)? {
        Ok(())
    } else {
        Err(io::Error::other(format!("{what} failed")))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn text() -> String {
        toolchain_text(
            Path::new("C:/repo"),
            &arch::X86_64,
            Path::new("C:/repo/.xtask/debug/xtask.exe"),
            Path::new("C:/llvm/bin/lld.exe"),
        )
    }

    #[test]
    fn the_toolchain_file_is_linux_not_generic() {
        // `Generic` leaves `LLVM_ON_UNIX` off, and `file_status` then compiles
        // Windows code paths for a guest that has none.
        let text = text();
        assert!(text.contains("set(CMAKE_SYSTEM_NAME Linux)"));
        assert!(!text.contains("Generic"));
    }

    #[test]
    fn the_toolchain_file_names_the_triple_and_the_arch() {
        let text = text();
        assert!(text.contains("set(CMAKE_C_COMPILER_TARGET \"x86_64-unknown-none\")"));
        // The bases come from `minix_ld`'s own `--arch` table, not from here.
        assert!(text.contains("minix-ld --arch x86"));
    }

    #[test]
    fn the_link_rule_is_xtask_minix_ld_with_every_input() {
        let text = text();
        assert!(text.contains("minix-ld --arch x86"));
        for input in [
            "--crt0",
            "--libc",
            "--libstdcxx",
            "--script",
            "--lld",
            "CMAKE_CXX_LINK_EXECUTABLE",
        ] {
            assert!(text.contains(input), "{input} missing from the link rule");
        }
    }

    #[test]
    fn the_configure_names_the_generated_toolchain_file() {
        let args = cmake_args(Path::new("repo"), &arch::X86_64, Path::new("host/bin"));
        assert!(
            args.iter()
                .any(|arg| arg == "-DCMAKE_TOOLCHAIN_FILE=repo/target/llvm-x86/toolchain.cmake"),
            "no toolchain file in {args:?}"
        );
    }

    #[test]
    fn the_configure_answers_every_test_it_cannot_run() {
        let args = cmake_args(Path::new("repo"), &arch::X86_64, Path::new("host/bin"));
        for option in [
            "-DCMAKE_CROSSCOMPILING=ON",
            "-DLLVM_ENABLE_THREADS=OFF",
            "-DLLVM_ENABLE_EH=OFF",
            "-DLLVM_ENABLE_RTTI=OFF",
            "-DHAVE_CXX_ATOMICS_WITHOUT_LIB=1",
            "-DHAVE_CXX_ATOMICS64_WITHOUT_LIB=1",
            "-DLLVM_HAS_ATOMICS=1",
            "-DLLVM_BUILD_TOOLS=OFF",
            "-DLLVM_ENABLE_PROJECTS=clang;lld",
            "-DLLVM_TARGETS_TO_BUILD=X86",
            "-DLLVM_DEFAULT_TARGET_TRIPLE=x86_64-unknown-none",
        ] {
            assert!(args.contains(&option.to_string()), "{option} missing");
        }
    }

    #[test]
    fn the_resource_directory_is_the_llvm_major() {
        assert_eq!(resource_major("23.1.1"), "23");
        assert_eq!(resource_major("23"), "23");
    }

    #[test]
    fn the_staged_root_is_the_one_the_gate_boots() {
        let stage = stage_root(Path::new("repo"), &arch::X86_64);
        let text = stage.display().to_string().replace('\\', "/");
        assert!(text.ends_with("target/toolchain/x86/root"), "{text}");
    }

    #[test]
    fn an_arch_without_a_carried_toolchain_is_refused_by_name() {
        let error = run(Path::new("repo"), Some("aarch64")).unwrap_err();
        assert!(error.to_string().contains("no toolchain build for aarch64"), "{error}");
    }
}
