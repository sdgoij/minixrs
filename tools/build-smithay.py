#!/usr/bin/env python3
"""Type-check smithay for the minix targets, against the forked crates.

`smithay` itself is never modified: it is fetched at a pinned revision into
`target/smithay` and built from a generated workspace (`target/smithay-probe`)
whose `[patch.crates-io]` points every OS-keyed crate at this tree's fork
(`libc`, `rustix`, `polling`, `calloop`, `errno`, and the wayland-rs family).
The OS-side additions that make it compile unmodified -- `std::os::minix`,
`std::os::unix`, epoll, `sigaction` -- live in those forks and in
`.notes/wayland.md` §6.13.

Usage: python tools/build-smithay.py [all|x86|riscv64|aarch64|<triple>] [--build]
                                    (default: x86_64-pc-minix, `cargo check`)

`--build` compiles rlibs instead of running `cargo check`. Neither mode links an
executable, so `libxkbcommon` (which `xkbcommon` links with `-lxkbcommon`) is
not needed yet; the compositor that pulls one in is 4d.

Runs on any host with a stage1 for it (`just bootstrap` or `just fetch-stage1`):
the rustc is looked up by this host's name, and the cargo artifacts are kept in
`target/smithay-probe/target-<host>/` so a Windows and a WSL build of the same
checkout cannot mix.

Prerequisites: the fork's stage1 compiler with this tree's std, and the
wayland-rs submodule's own submodules
(`git submodule update --init --recursive`).

Outputs: `target/smithay` (the pinned checkout) and `target/smithay-probe`
(the generated workspace).
"""

from __future__ import annotations

import os
import pathlib
import platform
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

from ccarch import ALL, resolve  # noqa: E402

SMITHAY_REPO = "https://github.com/Smithay/smithay"
SMITHAY_TAG = "v0.7.0"
SMITHAY_COMMIT = "a166cf4c94b5aedc332a65aa1dd753e8148829c3"
"""The revision every measurement in `.notes/wayland.md` §6.13 was taken at.

The tag is not enough on its own: the checkout is verified against this sha, so
a moved tag cannot silently change what the gate compiles.
"""

SMITHAY_DIR = ROOT / "target" / "smithay"
PROBE_DIR = ROOT / "target" / "smithay-probe"

CARGO_TARGET = PROBE_DIR / f"target-{platform.system().lower()}"
"""Per host on purpose: the host artifacts (build scripts, proc macros) share
`<target>/debug/deps`, so one checkout built from Windows and from WSL would
otherwise mix them."""

PATCHES = {
    # Our own stand-in for `errno` (it has no minix arm).
    "errno": "../../crates/errno",
    # The ecosystem forks, all submodules at the repo root.
    "libc": "../../libc",
    "rustix": "../../rustix",
    "polling": "../../polling",
    "calloop": "../../calloop",
    # The wayland-rs family is patched together: the protocol crates generate
    # code against the server API, so a half-patched family pairs two versions
    # of it.
    "wayland-sys": "../../wayland-rs/wayland-sys",
    "wayland-scanner": "../../wayland-rs/wayland-scanner",
    "wayland-backend": "../../wayland-rs/wayland-backend",
    "wayland-server": "../../wayland-rs/wayland-server",
    "wayland-protocols": "../../wayland-rs/wayland-protocols",
    "wayland-protocols-wlr": "../../wayland-rs/wayland-protocols-wlr",
    "wayland-protocols-misc": "../../wayland-rs/wayland-protocols-misc",
}

GENERATED = """\
# Generated by tools/build-smithay.py -- edits here are overwritten.
#
# A workspace of our own is what makes `[patch.crates-io]` legal: patches are
# read from the workspace root, and smithay is a path dependency inside it.
[workspace]

[package]
name = "smithay-probe"
version = "0.0.0"
edition = "2021"

[dependencies]
smithay = {{ path = "../smithay", default-features = false, features = ["wayland_frontend"] }}

[patch.crates-io]
{patches}
"""

SURFACE_PROBE = """\
pub fn surface() -> usize {{
    core::mem::size_of::<std::os::minix::net::UnixStream>()
}}
"""


def die(message: str) -> None:
    sys.exit(f"error: {message}")


def run(command: list[str], cwd: pathlib.Path | None = None,
        env: dict[str, str] | None = None) -> None:
    """Run *command*, letting its output through, and die if it fails."""
    result = subprocess.run(command, cwd=cwd, env=env)
    if result.returncode != 0:
        die(f"{' '.join(command)} exited {result.returncode}")


def output(command: list[str], cwd: pathlib.Path | None = None) -> str:
    result = subprocess.run(command, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        die(f"{' '.join(command)} failed: {result.stderr.strip()}")
    return result.stdout.strip()


def find_stage1_rustc() -> pathlib.Path:
    """The fork's stage1 rustc for *this* host, under `rust/build/<host>/stage1`.

    The name is keyed to the running host: a tree can hold a Windows stage1 and
    a Linux one at the same time (a checkout on a shared volume), and picking
    the wrong one fails much later, in the sysroot.
    """
    name = "rustc.exe" if os.name == "nt" else "rustc"
    for host in sorted((ROOT / "rust" / "build").glob("*")):
        candidate = host / "stage1" / "bin" / name
        if candidate.is_file():
            return candidate
    die("no stage1 rustc for this host under rust/build/*/stage1/bin -- "
        "run `just bootstrap`")


def check_stage1_surface(rustc: pathlib.Path, triple: str) -> None:
    """Ask the stage1 sysroot for `std::os::minix`, which this tree's std owns.

    Without it the build fails inside std's own `os/mod.rs` with "cannot find
    `unix` in `os`", which reads like a bug in the tree rather than a stale
    toolchain. A capability probe says what to do instead.
    """
    sync_target_with_stage1(rustc)
    probe = CARGO_TARGET / "stage1-surface.rs"
    probe.parent.mkdir(parents=True, exist_ok=True)
    probe.write_text(SURFACE_PROBE, encoding="utf-8")
    result = subprocess.run(
        [str(rustc), "--crate-type", "lib", "--emit=metadata", "--target", triple,
         "-o", str(probe.with_suffix(".rmeta")), str(probe)],
        capture_output=True, text=True)
    if result.returncode != 0:
        die(f"the {triple} sysroot in this stage1 has no `std::os::minix`, so it "
            "predates this tree's std -- rebuild it (`just bootstrap`) or fetch "
            "the release (`just fetch-stage1`)")


def sync_target_with_stage1(rustc: pathlib.Path) -> None:
    """Clear the cargo artifacts when the stage1 changed underneath them.

    Cargo invalidates a build by the compiler's version string, and every stage1
    this tree installs reports the same one (`1.100.0-dev`, `commit-hash:
    unknown` for a source build). Replacing the toolchain -- which `just
    fetch-stage1` does on every new rust pin -- therefore leaves host artifacts
    built against the previous sysroot, and the build fails with "found possibly
    newer version of crate `std` which `cc` depends on" inside a build script.
    The stamp is the release marker, or the rustc file itself for a source build.
    """
    stage1 = rustc.parent.parent
    marker = stage1 / ".minixrs-fetched"
    if marker.is_file():
        stamp = marker.read_text(encoding="utf-8").strip()
    else:
        stat = rustc.stat()
        stamp = f"source:{stat.st_mtime_ns}:{stat.st_size}"

    stamp_file = CARGO_TARGET / ".stage1-stamp"
    recorded = (stamp_file.read_text(encoding="utf-8").strip()
                if stamp_file.is_file() else None)
    if recorded != stamp and CARGO_TARGET.is_dir() and any(CARGO_TARGET.iterdir()):
        print("stage1 changed since the last build -- clearing the cargo artifacts")
        shutil.rmtree(CARGO_TARGET, ignore_errors=True)
    CARGO_TARGET.mkdir(parents=True, exist_ok=True)
    stamp_file.write_text(stamp, encoding="utf-8")


def check_submodules() -> None:
    """Fail early if the wayland-rs fork's protocol XML is not checked out.

    `wayland-protocols*` is a path patch into that submodule, and its protocol
    files are *nested* submodules; without them the build dies inside a proc
    macro on a missing `.xml`, which reads like a code error.
    """
    protocols = ROOT / "wayland-rs" / "wayland-protocols" / "protocols" / "stable"
    if not protocols.is_dir():
        die("wayland-rs's nested submodules are missing -- run "
            "`git -C wayland-rs submodule update --init --recursive`")


def ensure_smithay() -> None:
    """Fetch the pinned checkout, or move the existing one onto the pin."""
    if not (SMITHAY_DIR / ".git").is_dir():
        if SMITHAY_DIR.exists():
            shutil.rmtree(SMITHAY_DIR)
        print(f"fetching smithay {SMITHAY_TAG} into {SMITHAY_DIR.relative_to(ROOT)}")
        run(["git", "clone", "--depth", "1", "--branch", SMITHAY_TAG,
             SMITHAY_REPO, str(SMITHAY_DIR)])

    head = output(["git", "rev-parse", "HEAD"], cwd=SMITHAY_DIR)
    if head != SMITHAY_COMMIT:
        print(f"moving smithay from {head[:12]} to the pin {SMITHAY_COMMIT[:12]}")
        run(["git", "fetch", "--depth", "1", "origin", SMITHAY_COMMIT], cwd=SMITHAY_DIR)
        run(["git", "checkout", "--force", SMITHAY_COMMIT], cwd=SMITHAY_DIR)
        head = output(["git", "rev-parse", "HEAD"], cwd=SMITHAY_DIR)
        if head != SMITHAY_COMMIT:
            die(f"smithay is at {head}, wanted {SMITHAY_COMMIT}")


def write_probe() -> None:
    """Regenerate the patched workspace. Cheap, so it is always rewritten."""
    (PROBE_DIR / "src").mkdir(parents=True, exist_ok=True)
    patches = "\n".join(f'{name} = {{ path = "{path}" }}'
                        for name, path in PATCHES.items())
    (PROBE_DIR / "Cargo.toml").write_text(GENERATED.format(patches=patches),
                                          encoding="utf-8")
    (PROBE_DIR / "src" / "lib.rs").write_text(
        "//! Pulls smithay's `wayland_frontend` tree into a minix build.\n",
        encoding="utf-8")


def main(argv: list[str]) -> int:
    build = False
    archs = []
    for arg in argv:
        if arg == "--build":
            build = True
        elif arg == "all":
            archs.extend(ALL)
        elif arg.startswith("-"):
            die(f"unknown option {arg!r}")
        else:
            archs.append(resolve(arg))
    if not archs:
        archs = [resolve("x86")]

    rustc = find_stage1_rustc()
    check_submodules()
    ensure_smithay()
    write_probe()

    env = dict(os.environ)
    env["RUSTC"] = str(rustc)
    # `getrandom` 0.3 selects a custom backend with a cfg, not a feature; nothing
    # in this tree registers one yet (only a binary can), which is fine for a
    # check and for rlibs.
    env["RUSTFLAGS"] = '--cfg getrandom_backend="custom"'
    env["CARGO_TARGET_DIR"] = str(CARGO_TARGET)

    mode = "build" if build else "check"
    for arch in archs:
        check_stage1_surface(rustc, arch.triple)
        print(f"cargo {mode} smithay for {arch.triple}")
        run(["cargo", mode, "--target", arch.triple], cwd=PROBE_DIR, env=env)
    print(f"smithay: {mode} ok for " + ", ".join(a.triple for a in archs))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
