#!/usr/bin/env python3
"""Regenerate the rust fork's `rust/config.toml` for the given minix arch.

Usage: python tools/rust-config.py [all|x86|riscv64|aarch64]   (default: all)

The fork's `config.toml` is gitignored, so `just bootstrap` calls this to
(re)create it deterministically before running x.py. The minix targets are
in STAGE0_MISSING_TARGETS, so bootstrap builds a stage1 compiler from
source, and that compiler needs LLVM - built from source as well, see the
`[llvm]` block in the generated config.

The build host triple is detected and always included in the target list:
x.py prunes std for any target not listed, and the host std is required to
run build scripts (e.g. the minixrs crates' build.rs) when compiling for a
minix target.

Each minix triple is listed with its `-dyn` form: the position-independent
target a shared object is built for (`tools/build-dynlibc.py`). Those are the
targets whose sysroot the `no-std` key narrows to `core` and `alloc`, because
a shared object links nothing else - see the `[target.<triple>]` sections this
writes, and `std_crates_for_make_run` in the fork's bootstrap.
"""

from __future__ import annotations

import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

ARCH_TO_TARGET = {
    "x86": "x86_64-pc-minix",
    "riscv64": "riscv64gc-unknown-minix",
    "aarch64": "aarch64-unknown-minix",
}

# The position-independent form of each triple, for code a loader maps as a
# shared object. It is a target of its own and not a `-C relocation-model`
# because the `core` and `alloc` it links against are what have to be built PIC;
# its spec lives beside the executable one in the fork
# (`compiler/rustc_target/src/spec/targets/*_minix_elf.rs`).
#
# The `-elf` suffix is not decoration. `bootstrap` asks cc-rs for a C compiler
# for *every* configured target, and cc-rs rejects a fourth component it does not
# recognise as an environment or ABI ("unknown environment/ABI `dyn`") — `-elf`
# is one it maps to neither, so the name is the executable triple plus a
# distinguishing suffix and nothing else. Every other spelling considered
# (`-dyn`, `-gnu`) either fails that parse or claims an ABI this target has no
# business claiming.
DYN_TARGET = {
    "x86_64-pc-minix": "x86_64-pc-minix-elf",
    "riscv64gc-unknown-minix": "riscv64gc-unknown-minix-elf",
    "aarch64-unknown-minix": "aarch64-unknown-minix-elf",
}


def detect_host() -> str:
    """Detect the build host triple via the default toolchain's rustc."""
    try:
        out = subprocess.run(
            ["rustc", "-vV"], capture_output=True, text=True, check=True
        ).stdout
    except (subprocess.CalledProcessError, FileNotFoundError):
        return ""
    for line in out.splitlines():
        if line.startswith("host: "):
            return line[6:].strip()
    return ""


def main(argv: list[str]) -> int:
    arch = argv[1] if len(argv) > 1 else "all"
    if arch == "all":
        minix_targets = list(ARCH_TO_TARGET.values())
    elif arch in ARCH_TO_TARGET:
        minix_targets = [ARCH_TO_TARGET[arch]]
    else:
        print(
            f"error: unknown arch {arch!r}; expected all|x86|riscv64|aarch64",
            file=sys.stderr,
        )
        return 2

    host = detect_host()
    dyn_targets = [DYN_TARGET[t] for t in minix_targets]
    targets = ([host] if host else []) + minix_targets + dyn_targets

    # A shared object is linked against `core` and `alloc` and nothing else, so
    # there is no reason to put the rest of std in its sysroot: `no-std` makes
    # bootstrap keep those two crates for the target.
    no_std = "".join(f"\n[target.{t}]\nno-std = true\n" for t in dyn_targets)

    config = f"""# Generated by tools/rust-config.py ({arch}) — rerun `just bootstrap` to
# regenerate, or hand-edit (subsequent bootstrap runs overwrite it).
# The host ({host}) is always listed so its std survives x.py's pruning.
# A position-independent (`-elf`) triple is listed so its PIC `core`/`alloc`
# exist at all, and the `no-std` sections below keep std out of its sysroot.

[llvm]
# Built from source. The CI LLVM artifacts are keyed to the upstream base
# commit and get purged upstream once that base ages out; when the lookup
# misses, bootstrap exits with "failed to download llvm from CI" instead of
# falling back. `if-unchanged` does not avoid that either - this tree is
# unmodified relative to upstream, so it takes the download path too.
download-ci-llvm = false
# Only the backends the host and the minix targets need. The default is 15
# targets plus 4 experimental ones and dominates a from-source build, so
# extend this list when a port adds an arch (the minix triples map to X86,
# RISCV and AArch64).
targets = "AArch64;RISCV;X86"

[build]
target = {targets!r}
{no_std}"""
    out = ROOT / "rust" / "config.toml"
    out.parent.mkdir(parents=True, exist_ok=True)
    # Explicit UTF-8: x.py reads config.toml as UTF-8, and the locale
    # encoding (cp1252 on Windows) would mangle non-ASCII bytes.
    out.write_text(config, encoding="utf-8")
    print(f"wrote {out} with targets {targets}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
