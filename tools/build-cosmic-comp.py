#!/usr/bin/env python3
"""Check the cosmic-comp fork against the forks.

cosmic-comp is carried as the `cosmic-comp/` submodule, at a revision that
contains the one `.notes/wayland.md` 6.13 measured, and built from a generated
workspace (`target/cosmic-comp-probe`) whose `[patch.crates-io]` points every
OS-keyed crate at this tree's fork, exactly as `tools/build-smithay.py` does for
smithay. The smithay checkout that script owns is this build's smithay too, so
run it (or just this script, which ensures it) first.

Usage: python tools/build-cosmic-comp.py [all|x86|riscv64|aarch64|<triple>]
                                  [--metadata|--check|--build]
                                        (default: x86_64-pc-minix, `--metadata`)

`--metadata` resolves the graph only: it is the measurement `.notes/wayland.md`
6.13 records (the shell's 641 packages), and it needs no stage1.
`--check` and `--build` compile for the minix target with the stage1 compiler.

Runs on any host with a stage1 for it (`just bootstrap` or `just fetch-stage1`).

Outputs: `target/cosmic-comp-probe` (the generated workspace).
"""

from __future__ import annotations

import importlib.util
import os
import pathlib
import platform
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

from ccarch import ALL, resolve  # noqa: E402

COSMIC_COMMIT = "6700a5d03f86983bbdb05c48e8190a9b46ff79ad"
"""The upstream revision `.notes/wayland.md` 6.13 was measured at. The fork must
contain it, so a branch that has lost the measurement cannot build silently."""

COSMIC_DIR = ROOT / "cosmic-comp"
PROBE_DIR = ROOT / "target" / "cosmic-comp-probe"
CARGO_TARGET = ROOT / "target" / f"cosmic-comp-target-{platform.system().lower()}"

# Additional patches on top of the smithay probe's table. cosmic-comp pulls two
# crates smithay does not name.
EXTRA_PATCHES = {
    # The published crate gates its Unix half on `cfg(unix)` and puts minix on
    # the unsupported platform; the fork carries the port arms.
    "tempfile": "../../crates/tempfile",
    # `libloading` is what `backend_egl` loads EGL with; its Unix half is
    # `cfg(unix)` and needs the target's `RTLD_*` values.
    "libloading": "../../rust_libloading",
}

# Patches of git dependencies are keyed by the repository URL, not
# `crates-io`, so they go in their own tables.
GIT_PATCHES = {
    # The settings store writes through this crate, and the published one
    # reaches rustix 0.38 (this tree forks 1.x).
    "https://github.com/jackpot51/rust-atomicwrites": {
        "atomicwrites": "../../crates/atomicwrites",
    },
}

GENERATED = """\
# Generated by tools/build-cosmic-comp.py -- edits here are overwritten.
#
# A workspace of our own is what makes `[patch.crates-io]` legal: patches are
# read from the workspace root, and cosmic-comp is a path dependency inside it.
[workspace]

[package]
name = "cosmic-comp-probe"
version = "0.0.0"
edition = "2021"

[dependencies]
# The shell at its own revision, with the system-integration features off: the
# port has no D-Bus, logind or systemd.
cosmic-comp = {{ path = "../../cosmic-comp", default-features = false }}

[patch.crates-io]
smithay = {{ path = "../smithay" }}
{patches}

{git_patches}
"""


def die(message: str) -> None:
    sys.exit(f"error: {message}")


def run(command: list[str], cwd: pathlib.Path | None = None,
        env: dict[str, str] | None = None) -> None:
    result = subprocess.run(command, cwd=cwd, env=env)
    if result.returncode != 0:
        die(f"{' '.join(command)} exited {result.returncode}")


def output(command: list[str], cwd: pathlib.Path | None = None) -> str:
    result = subprocess.run(command, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        die(f"{' '.join(command)} failed: {result.stderr.strip()}")
    return result.stdout.strip()


def load_smithay_tool():
    """Import `tools/build-smithay.py`, which owns the smithay pin and its edits.

    Importing keeps one source of truth for the pin: a cosmic-comp build and a
    smithay check cannot drift onto different revisions.
    """
    path = ROOT / "tools" / "build-smithay.py"
    spec = importlib.util.spec_from_file_location("build_smithay", path)
    if spec is None or spec.loader is None:
        die(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def ensure_cosmic() -> None:
    """Check that the submodule is present and still contains the measured revision."""
    if not (COSMIC_DIR / ".git").exists():
        die("cosmic-comp is not checked out: run `git submodule update --init cosmic-comp`")
    head = output(["git", "rev-parse", "HEAD"], cwd=COSMIC_DIR)
    contains = subprocess.run(["git", "merge-base", "--is-ancestor",
                               COSMIC_COMMIT, head], cwd=COSMIC_DIR)
    if contains.returncode != 0:
        die(f"cosmic-comp at {head[:12]} does not contain the measured revision "
            f"{COSMIC_COMMIT[:12]}")


def render_git_patches() -> str:
    """Render the `[patch."<url>"]` tables for the forked git dependencies.

    A git dependency is replaced through a table named after its repository, so
    each one needs its own header; these land after the `crates-io` entries.
    """
    tables = []
    for url, crates in GIT_PATCHES.items():
        lines = [f'[patch."{url}"]']
        lines.extend(f'{name} = {{ path = "{path}" }}'
                     for name, path in crates.items())
        tables.append("\n".join(lines))
    return "\n\n".join(tables)


def write_probe(smithay_tool) -> None:
    """Regenerate the patched workspace. Cheap, so it is always rewritten."""
    (PROBE_DIR / "src").mkdir(parents=True, exist_ok=True)
    patches = dict(smithay_tool.PATCHES)
    patches.update(EXTRA_PATCHES)
    rendered = "\n".join(f'{name} = {{ path = "{path}" }}'
                         for name, path in patches.items())
    manifest = GENERATED.format(patches=rendered,
                                git_patches=render_git_patches())
    (PROBE_DIR / "Cargo.toml").write_text(manifest.rstrip() + "\n", encoding="utf-8")
    (PROBE_DIR / "src" / "lib.rs").write_text(
        "//! Pulls cosmic-comp into a minix build.\n", encoding="utf-8")


def main(argv: list[str]) -> int:
    mode = "metadata"
    archs = []
    for arg in argv:
        if arg in ("--metadata", "--check", "--build"):
            mode = arg[2:]
        elif arg == "all":
            archs.extend(ALL)
        elif arg.startswith("-"):
            die(f"unknown option {arg!r}")
        else:
            archs.append(resolve(arg))
    if not archs:
        archs = [resolve("x86")]

    smithay_tool = load_smithay_tool()
    smithay_tool.check_submodules()
    smithay_tool.ensure_smithay()
    ensure_cosmic()
    write_probe(smithay_tool)

    if mode == "metadata":
        result = subprocess.run(
            ["cargo", "metadata", "--format-version=1", "--manifest-path",
             str(PROBE_DIR / "Cargo.toml")],
            capture_output=True, text=True)
        if result.returncode != 0:
            die(f"cargo metadata failed: {result.stderr.strip()}")
        import json
        count = len(json.loads(result.stdout)["packages"])
        print(f"cosmic-comp: graph resolves, {count} packages")
        return 0

    rustc = smithay_tool.find_stage1_rustc()
    env = dict(os.environ)
    env["RUSTC"] = str(rustc)
    # `getrandom` 0.3 selects a custom backend with a cfg, not a feature.
    env["RUSTFLAGS"] = '--cfg getrandom_backend="custom"'
    env["CARGO_TARGET_DIR"] = str(CARGO_TARGET)

    verb = "check" if mode == "check" else "build"
    for arch in archs:
        smithay_tool.check_stage1_surface(rustc, arch.triple)
        print(f"cargo {verb} cosmic-comp for {arch.triple}")
        run(["cargo", verb, "--target", arch.triple], cwd=PROBE_DIR, env=env)
    print(f"cosmic-comp: {verb} ok for " + ", ".join(a.triple for a in archs))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
